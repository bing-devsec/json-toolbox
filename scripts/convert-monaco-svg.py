"""Generate application-scoped, local SVG masks from the reviewed Monaco 0.52.2 font.

Maintenance only: fonttools==4.65.0. Glyph selection is pinned by the reviewed module/application scope. No network access.
The generated stylesheet is consumed by monaco-svg.mjs, not by the browser font
loader. Original contours/advances are preserved; SVG does not retain TTF hints.
"""
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.parse import quote
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'node_modules/monaco-editor/esm/vs/base/browser/ui/codicons/codicon/codicon.ttf'
SOURCE_SHA256 = '0f1d5219934e96e83b8db162d60b4d8c09b5de1e7d38031cbafe4a3c0f2889c9'
DESTINATION = ROOT / 'assets/icons/codicon-0.52.2.svg.css'

def generate():
    scope = json.loads((ROOT / 'reports/monaco-svg-scope.json').read_text())
    selected = {int(cp, 16) for cp in scope['glyphCodepoints']}
    data = SOURCE.read_bytes()
    assert sha256(data).hexdigest() == SOURCE_SHA256, 'Review the installed Monaco font first'
    font = TTFont(BytesIO(data), recalcBBoxes=False, recalcTimestamp=False)
    assert (font['head'].unitsPerEm, font['hhea'].ascent, font['hhea'].descent) == (300, 300, 0)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    assert len(cmap) == 462
    assert selected <= set(cmap), 'Scope contains a missing glyph'
    declarations = []
    for cp, name in sorted(cmap.items()):
        if cp not in selected: continue
        assert glyphs[name].width == 300, name
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, 0, 300)))
        svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 300"><path d="' + pen.getCommands() + '"/></svg>'
        declarations.append('--json-codicon-' + format(cp, 'x') + ':url("data:image/svg+xml,' + quote(svg, safe='/= :,-.') + '");')
    return '/*! Codicon 0.52.2 — Microsoft; see /fonts/LICENSE.codicon.txt. 52 application glyphs. Generated by scripts/convert-monaco-svg.py. */\n:root {\n' + '\n'.join(declarations) + '\n}\n'

if __name__ == '__main__':
    import argparse
    parser=argparse.ArgumentParser(); parser.add_argument('--write',action='store_true'); args=parser.parse_args()
    result=generate().encode()
    if args.write:
        DESTINATION.parent.mkdir(parents=True,exist_ok=True)
        DESTINATION.write_bytes(result)
    else:
        assert DESTINATION.read_bytes() == result, 'Generated SVG stylesheet differs'
    print(json.dumps({'codepoints':52,'bytes':len(result),'sha256':sha256(result).hexdigest()}))
